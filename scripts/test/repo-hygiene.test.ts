import { describe, expect, it } from "vitest";
import {
  brandName,
  eeSources,
  exists,
  filesContaining,
  frontmatter,
  gitTracked,
  glob,
  lines,
  read,
  repoFiles,
  settings,
  size,
} from "./helpers";

describe("repo hygiene", () => {
  it("CLAUDE.md exists and is under 200 lines", () => {
    expect(lines("CLAUDE.md")).toBeLessThanOrEqual(200);
  });

  it("claude settings deny reading .env files", () => {
    expect(settings().permissions.deny).toContain("Read(./.env*)");
  });

  it("CLA workflow and CLA.md exist", () => {
    expect(exists("CLA.md") && exists(".github/workflows/cla.yml")).toBe(true);
  });

  it("every file under packages/ee/src has the commercial license header", () => {
    for (const f of eeSources()) {
      expect(read(f).startsWith("// SPDX-License-Identifier: LicenseRef-DMS-Commercial"), f).toBe(
        true,
      );
    }
  });

  it("brand name appears only in brand/ and docs/", () => {
    expect(
      filesContaining(brandName(), {
        caseSensitive: true,
        exclude: [
          "brand/**",
          "docs/**",
          "README.md",
          "TRADEMARKS.md",
          "**/*.svg",
          "apps/web/public/**" /* generated by brand:sync */,
        ],
      }),
    ).toEqual([]);
  });

  it("every project skill exists with matching name", () => {
    for (const c of [
      "new-tenant-table",
      "new-api-route",
      "new-rule",
      "plan-next",
      "handoff",
      "verify",
    ]) {
      expect(exists(`.claude/skills/${c}/SKILL.md`), c).toBe(true);
      expect(frontmatter(`.claude/skills/${c}/SKILL.md`).name).toBe(c);
    }
  });

  it("no legacy .claude/commands folder", () => {
    expect(exists(".claude/commands")).toBe(false);
  });

  it("no .env file is tracked", () => {
    expect(gitTracked(".env*").filter((f) => f !== ".env.example")).toEqual([]);
  });

  it("no *.env file is tracked either", () => {
    expect(gitTracked("*.env")).toEqual([]);
  });

  it("env example holds placeholders, never secret values", () => {
    const secretKeys = /PASSWORD|SECRET|MASTER_KEY|TOKEN/;
    for (const line of read(".env.example").split("\n")) {
      if (line.startsWith("#") || !line.includes("=")) continue;
      const [key = "", value = ""] = line.split(/=(.*)/s);
      if (secretKeys.test(key)) expect(value, key).toBe("");
      if (key.startsWith("DATABASE_URL")) expect(value, key).toMatch(/:__[A-Z_]+__@/);
    }
  });

  it("@dms/db/testing (owner-role test helpers) is imported only by tests", () => {
    const offenders = repoFiles().filter(
      (f) =>
        /\.(m?[jt]sx?)$/.test(f) &&
        !/(^|\/)test\//.test(f) &&
        !/vitest\.config\.ts$/.test(f) &&
        read(f).includes("@dms/db/testing"),
    );
    expect(offenders).toEqual([]);
  });

  it("brand SVGs carry no embedded metadata", () => {
    for (const f of glob("brand/assets/*.svg")) {
      expect(read(f), f).not.toMatch(/<metadata|c2pa/i);
    }
    expect(size("brand/assets/logo-mark.svg")).toBeLessThan(2048);
  });
});
