// pnpm brand:sync — regenerates every brand-derived file from brand/ (run after editing brand/).
// Outputs: apps/web/public/{favicon.svg,manifest.webmanifest}, packages/ui/src/brand.css and the
// generated header block in README.md. PNG icons are added in Plan 1 Task 13 (Playwright).
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { type Brand, brand } from "../src/index";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const out = (p: string) => {
  const full = join(ROOT, p);
  mkdirSync(dirname(full), { recursive: true });
  return full;
};
const GENERATED = "Generated by `pnpm brand:sync` from brand/brand.json. Do not edit.";

export function manifest(b: Brand): string {
  const m = {
    name: b.name,
    short_name: b.shortName,
    description: b.description,
    start_url: "/",
    scope: "/",
    display: "standalone",
    background_color: b.colors.paper,
    theme_color: b.colors.primary,
    icons: [{ src: "/favicon.svg", sizes: "any", type: "image/svg+xml", purpose: "any" }],
  };
  return `${JSON.stringify(m, null, 2)}\n`;
}

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

export function brandCss(b: Brand): string {
  const colors = Object.entries(b.colors)
    .map(([k, v]) => `  --brand-${kebab(k)}: ${v};`)
    .join("\n");
  return `/* ${GENERATED} */
:root {
${colors}
  --brand-font: "${b.font.family}", ${b.font.fallback};
}
`;
}

const html = (s: string) => s.replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`);

export function readmeHeader(raw: Brand): string {
  // The schema already forbids markup characters; escaping is a second layer.
  const b = { ...raw, name: html(raw.name), tagline: html(raw.tagline) };
  return `<!-- brand:start (${GENERATED}) -->
<p align="center">
  <picture>
    <source media="(prefers-color-scheme: dark)" srcset="brand/${b.logo.wordmarkDark}">
    <img alt="${b.name}" src="brand/${b.logo.wordmark}" height="56">
  </picture>
</p>
<p align="center"><strong>${b.tagline}</strong></p>
${b.status === "placeholder" ? `<p align="center"><em>${b.name} is a working name, not final. See <a href="TRADEMARKS.md">TRADEMARKS.md</a>.</em></p>\n` : ""}<!-- brand:end -->`;
}

/** Replaces the block between the brand markers, or prepends it when the markers are missing. */
export function withHeader(readme: string, header: string): string {
  const re = /<!-- brand:start[\s\S]*?<!-- brand:end -->/;
  return re.test(readme) ? readme.replace(re, header) : `${header}\n\n${readme}`;
}

/** Reads a file, or "" if it does not exist (no exists-then-read race). */
function readOrEmpty(path: string): string {
  try {
    return readFileSync(path, "utf8");
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === "ENOENT") return "";
    throw e;
  }
}

function main() {
  copyFileSync(join(ROOT, "brand", brand.logo.favicon), out("apps/web/public/favicon.svg"));
  writeFileSync(out("apps/web/public/manifest.webmanifest"), manifest(brand));
  writeFileSync(out("packages/ui/src/brand.css"), brandCss(brand));
  const readmePath = join(ROOT, "README.md");
  writeFileSync(readmePath, withHeader(readOrEmpty(readmePath), readmeHeader(brand)));
  console.warn("brand:sync wrote favicon, manifest, brand.css and the README header");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
